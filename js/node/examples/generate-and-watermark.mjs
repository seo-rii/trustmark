// Watermarking step for an image-generation tool, e.g. a tool that an LLM agent calls.
//
// The generator (any model or service) returns image bytes; this step embeds a TrustMark
// watermark, encodes the final format and returns the new bytes. If anything fails, the tool
// fails: it never falls back to returning the unwatermarked image.
//
// Run from js/node, with encoder_Q.onnx in TRUSTMARK_MODEL_DIR:
//   TRUSTMARK_MODEL_DIR=/path/to/models node examples/generate-and-watermark.mjs in.png out.png
// The input file stands in for the generator's output.

import { randomBytes } from 'node:crypto';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const { createTrustmark } = require('..');  // require('trustmark-node') when installed as a dependency

// One instance per process: the ONNX sessions are created once and reused by every call.
let trustmark = null;
function getTrustmark() {
  trustmark ??= createTrustmark({
    modelDir: process.env.TRUSTMARK_MODEL_DIR,
    allowDownload: false,          // models are provisioned with the deployment
    executionProviders: ['cpu'],   // e.g. ['cuda', 'cpu'] on a GPU host
    maxConcurrency: 2,
  });
  return trustmark;
}

/**
 * A 61-bit BCH_5 payload. Here it is random; a real service would use an identifier it can
 * look up later (for example to find a C2PA manifest), always as a bit string.
 */
function newPayload(capacity) {
  return Array.from(randomBytes(Math.ceil(capacity / 8)), (byte) => byte.toString(2).padStart(8, '0')).join('').slice(0, capacity);
}

/**
 * The tool's post-processing step: generated bytes in, watermarked bytes out.
 *
 * @param {Uint8Array} generated - PNG or JPEG bytes from the generator.
 * @param {{format?: 'png'|'jpeg', quality?: number, signal?: AbortSignal}} [options]
 * @returns {Promise<{bytes: Buffer, mimeType: string, payload: string}>}
 */
export async function watermarkGeneratedImage(generated, { format = 'png', quality, signal } = {}) {
  const tm = getTrustmark();
  const result = await tm.encode(generated, newPayload(tm.capacity), { format, quality, signal });
  return { bytes: result.bytes, mimeType: result.mimeType, payload: result.payload };
}

async function main() {
  const [input, output] = process.argv.slice(2);
  if (!input || !output) {
    console.error('usage: node examples/generate-and-watermark.mjs <generated.png|jpg> <output.png|jpg>');
    process.exitCode = 2;
    return;
  }
  try {
    const generated = await fs.readFile(input);
    const format = /\.jpe?g$/i.test(output) ? 'jpeg' : 'png';
    const { bytes, payload } = await watermarkGeneratedImage(generated, { format, signal: AbortSignal.timeout(120000) });
    await fs.writeFile(output, bytes);
    console.log(`watermarked ${input} -> ${output} (payload ${payload})`);
  } catch (error) {
    console.error(`not watermarked: ${error.code || error.name}: ${error.message}`);
    process.exitCode = 1;
  } finally {
    if (trustmark) await trustmark.close();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
